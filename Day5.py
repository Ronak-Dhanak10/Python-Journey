# TYPECASTING IN PYTHON
# Typecasting is the process of converting one data type to another data type
# In python we can use the following functions for typecasting
# 1. int() : it converts a value to an integer
# 2. float() : it converts a value to a float
# 3. str() : it converts a value to a string
# 4. bool() : it converts a value to a boolean
# 5. complex() : it converts a value to a complex number
#  IN a python their are two types of typecasting
# 1. Implicit typecasting : it is done automatically by the python interpreter when we
# perform an operation on two different data types
# 2. Explicit typecasting : it is done manually by the programmer using the above functions
a = 27
b = 141248.0052
name = True 
hy = "Hello World"
n = complex(2,3)
print("The type of  a",type(a))
print("The type of  b",type(b))
print("The type of  name",type(name))
print("The type of  hy",type(hy))
print("The type of  n",type(n))